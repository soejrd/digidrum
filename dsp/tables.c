uint16_t dd_exp_decay_to_coeff(uint16_t decay_0_127)
{
    uint32_t idx = (uint32_t)decay_0_127 * (DD_EXP_SIZE - 1) / 127u;
    return (uint16_t)dd_exp_decay_tab[idx];
}

int32_t dd_decay_coeff_from_ms(uint32_t ms)
{
    uint32_t tau_samples;
    uint32_t idx;
    uint32_t frac;
    int32_t c0, c1;
    uint32_t sample_rate = 48000u;

    if (ms == 0)
        return 0;
    tau_samples = ms * sample_rate / 1000u;
    if (tau_samples == 0)
        return 0;

    if (tau_samples <= 4u)
        return dd_exp_decay_tab[0];
    if (tau_samples >= 4096u)
        return dd_exp_decay_tab[DD_EXP_SIZE - 1];

    idx = (tau_samples - 4u) * (DD_EXP_SIZE - 1) / (4096u - 4u);
    frac = ((tau_samples - 4u) * (DD_EXP_SIZE - 1)) % (4096u - 4u);
    c0 = dd_exp_decay_tab[idx];
    c1 = dd_exp_decay_tab[idx + 1];
    return c0 + ((c1 - c0) * (int32_t)frac >> 16);
}
